import { NextResponse } from 'next/server';
import { autoGenerateDraftsAction } from '@/app/actions';

export const dynamic = 'force-dynamic';

/**
 * Scheduled cron job to continuously turn recorded ideas, references,
 * and topics into polished posts awaiting creator approval (or auto-scheduled).
 */
export async function GET(request: Request) {
  try {
    const authHeader = request.headers.get('authorization');
    const cronSecret = process.env.CRON_SECRET;

    // Se houver CRON_SECRET configurado, valida a autorização
    if (cronSecret && authHeader !== `Bearer ${cronSecret}`) {
      const url = new URL(request.url);
      const queryKey = url.searchParams.get('key');
      if (queryKey !== cronSecret) {
        return NextResponse.json({ error: 'Não autorizado' }, { status: 401 });
      }
    }

    const result = await autoGenerateDraftsAction(3);

    if (result.error) {
      return NextResponse.json({ success: false, error: result.error }, { status: 500 });
    }

    return NextResponse.json({
      success: true,
      count: result.count,
      isAutonomous: result.isAutonomous,
      posts: result.posts,
      timestamp: new Date().toISOString(),
    });
  } catch (error: any) {
    return NextResponse.json(
      { success: false, error: error.message },
      { status: 500 }
    );
  }
}
